#!/usr/bin/env python3
"""Generate unicode_nfc.go from the Unicode character database.

Run from internal/text:  python3 gen_nfc.py > unicode_nfc.go
The generated file holds the canonical composition pairs and the canonical
combining classes that text.Normalize needs. Hangul syllables are handled
algorithmically and are therefore not listed.
"""
import sys
import unicodedata

HANGUL_FIRST, HANGUL_LAST = 0xAC00, 0xD7A3

pairs = {}
for cp in range(0x110000):
    if HANGUL_FIRST <= cp <= HANGUL_LAST:
        continue
    dec = unicodedata.decomposition(chr(cp))
    if not dec or dec.startswith("<"):
        continue
    parts = dec.split()
    if len(parts) != 2:
        continue
    first, second = int(parts[0], 16), int(parts[1], 16)
    if unicodedata.combining(chr(second)) == 0:
        continue
    pairs[(first, second)] = cp

classes = {}
for cp in range(0x110000):
    c = unicodedata.combining(chr(cp))
    if c:
        classes[cp] = c

out = sys.stdout
out.write("// Code generated by gen_nfc.py from Unicode %s; DO NOT EDIT.\n\n" % unicodedata.unidata_version)
out.write("package text\n\n")
out.write("// unicodeVersion is the Unicode release the tables below were generated from.\n")
out.write('const unicodeVersion = "%s"\n\n' % unicodedata.unidata_version)
out.write("// compositionPairs maps a starter and a combining mark to the precomposed\n")
out.write("// character they form. Every entry is one canonical decomposition step, so a\n")
out.write("// character that composes in several steps is reached step by step.\n")
out.write("var compositionPairs = map[[2]rune]rune{\n")
for (first, second), composed in sorted(pairs.items()):
    out.write("\t{0x%04X, 0x%04X}: 0x%04X,\n" % (first, second, composed))
out.write("}\n\n")
out.write("// combiningClasses maps every combining mark to its canonical combining\n")
out.write("// class. Non-zero classes order the marks of one character before composition.\n")
out.write("var combiningClasses = map[rune]uint8{\n")
for cp, c in sorted(classes.items()):
    out.write("\t0x%04X: %d,\n" % (cp, c))
out.write("}\n")
