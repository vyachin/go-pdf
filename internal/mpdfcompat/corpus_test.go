// Package mpdfcompat runs the HTML fixtures of the mPDF test suite through this
// engine.
//
// mPDF's own tests are PHPUnit tests: they assert PHP internals (Imagick
// snapshots, reflection, mPDF specific objects) and exercise features outside
// this engine's profile. Only the documents are portable, so this package is a
// compatibility and robustness suite:
//
//   - every fixture must be processed without a panic;
//   - fixtures inside the profile must produce a valid, deterministic PDF and
//     match their text golden;
//   - fixtures outside the profile must be rejected with diagnostics, not with
//     a crash and not silently.
//
// The corpus is generated by cmd/mpdfimport and committed, so tests run
// offline.
package mpdfcompat

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"runtime/debug"
	"sort"
	"strings"
	"testing"

	"github.com/vyachin/go-pdf/internal/diag"
	"github.com/vyachin/go-pdf/internal/engine"
	"github.com/vyachin/go-pdf/internal/pdfdebug"
)

var update = flag.Bool("update", false, "rewrite compatibility goldens")

type testCase struct {
	Name   string `json:"name"`
	Kind   string `json:"kind"`
	Source string `json:"source"`
	HTML   string `json:"html"`
	Skip   string `json:"skip"`
}

type corpus struct {
	Source string     `json:"source"`
	Note   string     `json:"note"`
	Cases  []testCase `json:"cases"`
}

func corpusPath() string {
	return filepath.Join("..", "..", "testdata", "mpdf", "cases.json")
}

func goldenDir() string {
	return filepath.Join("..", "..", "testdata", "mpdf", "golden")
}

func loadCorpus(t *testing.T) corpus {
	t.Helper()
	data, err := os.ReadFile(corpusPath())
	if err != nil {
		t.Fatalf("reading the mPDF corpus: %v\nrun: go run ./cmd/mpdfimport -src <mpdf>/tests -out testdata/mpdf", err)
	}
	var c corpus
	if err := json.Unmarshal(data, &c); err != nil {
		t.Fatalf("parsing %s: %v", corpusPath(), err)
	}
	if len(c.Cases) == 0 {
		t.Fatal("the mPDF corpus is empty")
	}
	return c
}

func testFont(t *testing.T) string {
	t.Helper()
	candidates := []string{}
	if p := os.Getenv("PDFTEST_FONT"); p != "" {
		candidates = append(candidates, p)
	}
	// The bundled font keeps the corpus identical on every platform and in CI.
	candidates = append(candidates, filepath.Join("..", "..", "testdata", "fonts", "DejaVuSans.ttf"))
	if runtime.GOOS == "darwin" {
		candidates = append(candidates,
			"/System/Library/Fonts/Supplemental/Arial.ttf",
			"/System/Library/Fonts/Supplemental/Times New Roman.ttf",
		)
	}
	candidates = append(candidates,
		"/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
		"/usr/share/fonts/truetype/liberation/LiberationSerif-Regular.ttf",
	)
	for _, p := range candidates {
		if _, err := os.Stat(p); err == nil {
			return p
		}
	}
	t.Skip("no TrueType font available; set PDFTEST_FONT")
	return ""
}

// convert runs the fixture and turns a panic into a test failure with a stack.
func convert(t *testing.T, c testCase, font string) (res engine.Result, err error) {
	t.Helper()
	defer func() {
		if r := recover(); r != nil {
			t.Fatalf("conversion panicked: %v\n%s", r, debug.Stack())
		}
	}()
	return engine.Convert(context.Background(), []byte(c.HTML), engine.Options{
		FallbackFont: font,
		File:         c.Source,
	})
}

func TestCorpus(t *testing.T) {
	c := loadCorpus(t)
	font := testFont(t)
	golden := goldenDir()
	seen := map[string]bool{}

	supported, rejected, skipped := 0, 0, 0
	rejectCodes := map[string]int{}
	var snapshotBlockers []string
	byKind := map[string][3]int{} // supported, rejected, skipped
	for _, tc := range c.Cases {
		tc := tc
		t.Run(tc.Name, func(t *testing.T) {
			if tc.Skip != "" {
				skipped++
				k := byKind[tc.Kind]
				k[2]++
				byKind[tc.Kind] = k
				t.Skip(tc.Skip)
			}
			if testing.Short() && len(tc.HTML) > 20000 {
				skipped++
				t.Skip("large fixture, skipped in -short mode")
			}
			seen[tc.Name] = true

			res, err := convert(t, tc, font)
			goldenPath := filepath.Join(golden, tc.Name+".txt")
			_, statErr := os.Stat(goldenPath)
			hasGolden := statErr == nil

			if err != nil {
				rejected++
				k := byKind[tc.Kind]
				k[1]++
				byKind[tc.Kind] = k
				for _, d := range res.Diagnostics {
					if d.Severity == diag.Error {
						rejectCodes[d.Code]++
						if tc.Kind == "snapshot" {
							snapshotBlockers = append(snapshotBlockers, fmt.Sprintf("%-32s %s", tc.Name, d.String()))
						}
						break
					}
				}
				if len(res.Diagnostics) == 0 {
					t.Fatalf("rejected without diagnostics: %v", err)
				}
				if hasGolden {
					t.Fatalf("regression: this fixture used to convert, now it is rejected: %s", res.Diagnostics.Lines()[0])
				}
				return
			}

			supported++
			k := byKind[tc.Kind]
			k[0]++
			byKind[tc.Kind] = k
			if !bytes.HasPrefix(res.PDF, []byte("%PDF-")) {
				t.Fatalf("output is not a PDF: %q", res.PDF[:min(8, len(res.PDF))])
			}
			// Determinism: the same fixture must produce the same bytes.
			again, err := convert(t, tc, font)
			if err != nil {
				t.Fatalf("second conversion failed: %v", err)
			}
			if !bytes.Equal(res.PDF, again.PDF) {
				t.Fatal("two conversions of the same fixture differ")
			}
			validatePDF(t, res.PDF)

			text, err := pdfdebug.Text(res.PDF)
			if err != nil {
				t.Fatalf("extracting text: %v", err)
			}
			if *update {
				if err := os.MkdirAll(golden, 0o755); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(goldenPath, []byte(text), 0o644); err != nil {
					t.Fatal(err)
				}
				return
			}
			if !hasGolden {
				t.Fatalf("missing golden %s; run go test ./internal/mpdfcompat -update", goldenPath)
			}
			want, err := os.ReadFile(goldenPath)
			if err != nil {
				t.Fatal(err)
			}
			if strings.TrimSpace(string(want)) != strings.TrimSpace(text) {
				t.Fatalf("text differs from the golden\n got: %q\nwant: %q", truncate(text, 300), truncate(string(want), 300))
			}
		})
	}

	// Goldens without a fixture are stale and must not accumulate.
	if entries, err := os.ReadDir(golden); err == nil {
		for _, e := range entries {
			if !strings.HasSuffix(e.Name(), ".txt") {
				continue
			}
			if name := strings.TrimSuffix(e.Name(), ".txt"); !seen[name] {
				t.Errorf("stale golden without a fixture: %s", e.Name())
			}
		}
	}

	t.Logf("mPDF corpus %s: %d converted, %d rejected by the profile, %d skipped",
		c.Source, supported, rejected, skipped)
	for _, kind := range []string{"issue", "snapshot"} {
		if k, ok := byKind[kind]; ok {
			t.Logf("  %-8s converted=%d rejected=%d skipped=%d", kind, k[0], k[1], k[2])
		}
	}
	codes := make([]string, 0, len(rejectCodes))
	for code := range rejectCodes {
		codes = append(codes, code)
	}
	sort.Strings(codes)
	for _, code := range codes {
		t.Logf("  rejected: %-28s %d", code, rejectCodes[code])
	}
	for _, line := range snapshotBlockers {
		t.Logf("  snapshot blocked: %s", line)
	}
}

// pdfcpuPath finds the independent validator. CI sets PDF_REQUIRE_VALIDATOR=1
// and installs pdfcpu, so a missing binary fails the build there; locally the
// check is reported as skipped instead.
func pdfcpuPath(t *testing.T) string {
	t.Helper()
	if bin := os.Getenv("PDFCPU"); bin != "" {
		return bin
	}
	if bin, err := exec.LookPath("pdfcpu"); err == nil {
		return bin
	}
	// Strict mode means "discoverable through PATH or PDFCPU"; the local
	// fallback below is a convenience that must not mask a missing tool in CI.
	if os.Getenv("PDF_REQUIRE_VALIDATOR") == "1" {
		t.Fatal("pdfcpu is required (PDF_REQUIRE_VALIDATOR=1) but was not found in PATH")
	}
	if st, err := os.Stat("/tmp/gobin/pdfcpu"); err == nil && !st.IsDir() {
		return "/tmp/gobin/pdfcpu"
	}
	t.Log("pdfcpu not available, skipping independent validation")
	return ""
}

func validatePDF(t *testing.T, data []byte) {
	t.Helper()
	bin := pdfcpuPath(t)
	if bin == "" {
		return
	}
	path := filepath.Join(t.TempDir(), "case.pdf")
	if err := os.WriteFile(path, data, 0o644); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(bin, "validate", path)
	cmd.Env = append(os.Environ(), "HOME="+filepath.Dir(path))
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("pdfcpu validate failed: %v\n%s", err, out)
	}
}

func truncate(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "..."
}
